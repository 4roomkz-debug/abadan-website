/** «Директор филиала в Актау, Kaspi Bank» — или только компания, если должности в письме нет. */
export function signature(t: Testimonial): string {
  const company = t.company.charAt(0).toUpperCase() + t.company.slice(1);
  return t.role ? `${t.role}, ${t.company}` : company;
}
